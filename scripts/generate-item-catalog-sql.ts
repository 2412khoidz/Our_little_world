import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { catalogFingerprint } from '../src/shared/economy/catalogConfig.ts';
import { buildUnifiedCatalogRows } from '../src/shared/catalog/canonicalCatalog.ts';

const sqlStr = (value: string) => "'" + value.replaceAll("'", "''") + "'";
const sqlJson = (value: unknown) => sqlStr(JSON.stringify(value)) + '::jsonb';

const rows = buildUnifiedCatalogRows();
const fingerprint = catalogFingerprint();

const insertStatements = [
  'INSERT INTO public.item_catalog (sku, name_vi, description_vi, purpose, stack_limit, tradeable, category, icon_id, sell_price, buy_price, sources, uses, quality_tiers, donor_source) VALUES',
  rows
    .map(
      (r, idx) =>
        `  (${sqlStr(r.sku)}, ${sqlStr(r.nameVi)}, ${sqlStr(r.descriptionVi)}, ${sqlStr(r.purpose)}, ${r.stackLimit}, ${r.tradeable}, ${sqlStr(r.category)}, ${sqlStr(r.iconId)}, ${r.sellPrice}, ${r.buyPrice === null ? 'NULL' : r.buyPrice}, ${sqlJson(r.sources)}, ${sqlJson(r.uses)}, ${sqlJson(r.qualityTiers)}, ${sqlStr(r.donorSource)})${idx === rows.length - 1 ? '' : ','}`,
    )
    .join('\n'),
  'ON CONFLICT (sku) DO UPDATE SET',
  '  name_vi = EXCLUDED.name_vi,',
  '  description_vi = EXCLUDED.description_vi,',
  '  purpose = EXCLUDED.purpose,',
  '  stack_limit = EXCLUDED.stack_limit,',
  '  tradeable = EXCLUDED.tradeable,',
  '  category = EXCLUDED.category,',
  '  icon_id = EXCLUDED.icon_id,',
  '  sell_price = EXCLUDED.sell_price,',
  '  buy_price = EXCLUDED.buy_price,',
  '  sources = EXCLUDED.sources,',
  '  uses = EXCLUDED.uses,',
  '  quality_tiers = EXCLUDED.quality_tiers,',
  '  donor_source = EXCLUDED.donor_source;',
].join('\n');

if (process.argv.includes('--write')) {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const repoRoot = path.resolve(here, '..');
  const jsonPath = path.join(repoRoot, 'src', 'shared', 'catalog', 'canonicalCatalog.generated.json');
  const sqlPath = path.join(
    repoRoot,
    'supabase',
    'migrations',
    '20261127000100_deep_farming_canonical_catalog.sql',
  );

  const jsonPayload = {
    fingerprint,
    totalItems: rows.length,
    items: rows.map((r) => ({
      sku: r.sku,
      nameVi: r.nameVi,
      descriptionVi: r.descriptionVi,
      purpose: r.purpose,
      stackLimit: r.stackLimit,
      tradeable: r.tradeable,
      category: r.category,
      iconId: r.iconId,
      sellPrice: r.sellPrice,
      buyPrice: r.buyPrice,
      sources: r.sources,
      uses: r.uses,
      qualityTiers: r.qualityTiers,
      donorSource: r.donorSource,
    })),
  };
  fs.writeFileSync(jsonPath, JSON.stringify(jsonPayload, null, 2) + '\n', 'utf8');

  const purposes = [...new Set(rows.map((r) => r.purpose))].sort();
  const migrationSql = [
    '-- Checkpoint A: Canonical Deep Farming Item Catalog (single source sync)',
    `-- Generated by scripts/generate-item-catalog-sql.ts (${rows.length} items, fingerprint ${fingerprint})`,
    '',
    'DO $$',
    'DECLARE',
    '  v_constraint text;',
    'BEGIN',
    '  FOR v_constraint IN',
    '    SELECT conname',
    '    FROM pg_constraint',
    "    WHERE conrelid = 'public.item_catalog'::regclass",
    "      AND contype = 'c'",
    "      AND pg_get_constraintdef(oid) LIKE '%purpose%'",
    '  LOOP',
    "    EXECUTE format('ALTER TABLE public.item_catalog DROP CONSTRAINT %I', v_constraint);",
    '  END LOOP;',
    'END $$;',
    '',
    'ALTER TABLE public.item_catalog',
    `  ADD CONSTRAINT item_catalog_purpose_check CHECK (purpose IN (${purposes.map(sqlStr).join(', ')})),`,
    "  ADD COLUMN IF NOT EXISTS category text NOT NULL DEFAULT 'ingredient',",
    "  ADD COLUMN IF NOT EXISTS icon_id text NOT NULL DEFAULT '',",
    '  ADD COLUMN IF NOT EXISTS sell_price integer NOT NULL DEFAULT 0,',
    '  ADD COLUMN IF NOT EXISTS buy_price integer NULL,',
    "  ADD COLUMN IF NOT EXISTS sources jsonb NOT NULL DEFAULT '[]'::jsonb,",
    "  ADD COLUMN IF NOT EXISTS uses jsonb NOT NULL DEFAULT '[]'::jsonb,",
    '  ADD COLUMN IF NOT EXISTS quality_tiers jsonb NOT NULL DEFAULT \'["normal"]\'::jsonb,',
    "  ADD COLUMN IF NOT EXISTS donor_source text NOT NULL DEFAULT '';",
    '',
    insertStatements,
    '',
  ].join('\n');
  fs.writeFileSync(sqlPath, migrationSql, 'utf8');
  console.log(`Synced ${rows.length} items (fingerprint ${fingerprint}) -> JSON + SQL migration`);
} else {
  console.log('-- Generated from src/shared/catalog/canonicalCatalog.ts (single source).');
  console.log('-- Economy catalog fingerprint: ' + fingerprint);
  console.log(insertStatements);
}
