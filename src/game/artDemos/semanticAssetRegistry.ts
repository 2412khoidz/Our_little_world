/**
 * Semantic Asset ID Registry & Compatibility Contract for Our Little World.
 *
 * Maps logical game/catalog IDs (independent of tileset pack coordinates) to
 * exact pixel source rectangles, anchors, shadows, collision footprints,
 * interaction spots, furniture collection themes, and verified license notes.
 */

export type AssetCollectionTheme = 'pastel' | 'modern' | 'cottage' | 'rustic';

export type AssetLayerSlot = 'ground' | 'water' | 'floor' | 'wall' | 'prop' | 'canopy' | 'actor';

export interface SemanticAssetSpec {
  id: string;
  labelVi: string;
  sourcePack:
    | 'sprout-lands-basic'
    | 'sprout-lands-sorry'
    | 'modern-interiors-free'
    | 'cozy-lands-basic'
    | 'sunnyside-world'
    | 'free-pets-pack';
  textureKey: string;
  rect: { x: number; y: number; w: number; h: number };
  logicalTiles: { w: number; h: number };
  anchor: { ox: number; oy: number };
  layer: AssetLayerSlot;
  collection: AssetCollectionTheme;
  shadow?: { w: number; h: number; offsetY?: number };
  collisionTiles?: { dx: number; dy: number; w: number; h: number };
  interactionOffsetPx?: { dx: number; dy: number };
  licenseNote: string;
}

